#!/usr/bin/env python3
"""
Issue Formatter - Format plans as ZTE-compatible GitHub issues.
"""

from dataclasses import dataclass, field
from typing import List, Optional, Dict, Any
from enum import Enum
import subprocess
import json
from datetime import datetime


class IssueType(Enum):
    """GitHub issue types for ZTE."""
    FEATURE = "/feature"
    BUG = "/bug"
    CHORE = "/chore"
    ENHANCEMENT = "/enhancement"


@dataclass
class PlanSection:
    """A section of an implementation plan."""
    title: str
    content: str
    files: List[str] = field(default_factory=list)


@dataclass
class FormattedIssue:
    """A ZTE-formatted GitHub issue."""
    title: str
    body: str
    labels: List[str] = field(default_factory=list)
    issue_type: IssueType = IssueType.FEATURE


class IssueFormatter:
    """
    Formats implementation plans as ZTE-compatible GitHub issues.
    """

    TEMPLATE = '''## Description
{description}

## Implementation Plan
{plan_steps}

## Files to Modify
{files_list}

## Acceptance Criteria
{acceptance_criteria}

---
{issue_type}

**Generated by Skills-on-Top-of-ZTE**
**Confidence Score**: {confidence}%
'''

    def __init__(self, repo: str = "craigmbrown/ETAC-System"):
        self.repo = repo

    def format_issue(
        self,
        title: str,
        description: str,
        plan_steps: List[str],
        files: List[str],
        acceptance_criteria: List[str],
        issue_type: IssueType = IssueType.FEATURE,
        confidence: float = 0.85
    ) -> FormattedIssue:
        """
        Format a plan as a ZTE-compatible issue.

        Args:
            title: Issue title
            description: Brief description
            plan_steps: Implementation steps
            files: Files to modify
            acceptance_criteria: Definition of done
            issue_type: Type of issue
            confidence: Planning confidence score

        Returns:
            FormattedIssue ready for creation
        """
        # Format plan steps
        plan_content = "\n".join(f"- [ ] {step}" for step in plan_steps)

        # Format files list
        files_content = "\n".join(f"- `{f}`" for f in files)

        # Format acceptance criteria
        criteria_content = "\n".join(f"- [ ] {c}" for c in acceptance_criteria)

        body = self.TEMPLATE.format(
            description=description,
            plan_steps=plan_content,
            files_list=files_content,
            acceptance_criteria=criteria_content,
            issue_type=issue_type.value,
            confidence=int(confidence * 100)
        )

        return FormattedIssue(
            title=title,
            body=body,
            labels=["zte-ready", issue_type.name.lower()],
            issue_type=issue_type
        )

    def create_issue(self, formatted: FormattedIssue) -> Optional[int]:
        """
        Create a GitHub issue using gh CLI.

        Returns:
            Issue number if successful, None otherwise
        """
        cmd = [
            "gh", "issue", "create",
            "--repo", self.repo,
            "--title", formatted.title,
            "--body", formatted.body
        ]

        for label in formatted.labels:
            cmd.extend(["--label", label])

        try:
            result = subprocess.run(
                cmd, capture_output=True, text=True, check=True
            )
            # Extract issue number from URL
            url = result.stdout.strip()
            if url and "/" in url:
                return int(url.split("/")[-1])
            return None
        except subprocess.CalledProcessError as e:
            print(f"Failed to create issue: {e.stderr}")
            return None

    def format_from_consensus(
        self,
        consensus: Dict[str, Any]
    ) -> FormattedIssue:
        """
        Format from multi-model consensus output.

        Args:
            consensus: Consensus result from multi-model planner

        Returns:
            FormattedIssue
        """
        return self.format_issue(
            title=consensus.get("title", "Enhancement Request"),
            description=consensus.get("summary", ""),
            plan_steps=consensus.get("steps", []),
            files=consensus.get("files", []),
            acceptance_criteria=consensus.get("criteria", []),
            issue_type=IssueType(consensus.get("type", "/feature")),
            confidence=consensus.get("confidence", 0.85)
        )


# Standard I/O Pattern compliance
if __name__ == "__main__":
    formatter = IssueFormatter()
    print("SUCCESS: issue_formatter module loaded")
    print(f"Repo: {formatter.repo}")
    print(f"Issue types: {[t.value for t in IssueType]}")

    # Test formatting
    issue = formatter.format_issue(
        title="Test Issue",
        description="Test description",
        plan_steps=["Step 1", "Step 2"],
        files=["file1.py", "file2.py"],
        acceptance_criteria=["Tests pass"],
        confidence=0.92
    )
    print(f"Formatted title: {issue.title}")
    print(f"Labels: {issue.labels}")
